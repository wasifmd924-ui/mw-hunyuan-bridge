"""
MW Hunyuan Bridge - Optional Windows SketchUp Integration Helper
=================================================================
Security-first local bridge that:
1. Detects installed SketchUp versions on Windows.
2. Handles `mwhunyuan://open?file=<local_dae_path>` custom protocol launches.
3. Validates that the target path is a real, existing local .dae file (rejects remote URLs,
   UNC paths, non-.dae files, and unsafe arguments).
4. Never executes arbitrary commands received from a browser.
5. Optionally serves a localhost-only health endpoint on 127.0.0.1:48921 so the web UI
   can verify helper availability honestly.
"""

from __future__ import annotations

import argparse
import glob
import http.server
import json
import os
import re
import subprocess
import sys
import tempfile
import urllib.parse
from pathlib import Path
from typing import Optional

HELPER_PORT = 48921
ALLOWED_EXTENSIONS = {".dae"}
UNSAFE_CHARS_PATTERN = re.compile(r'[\x00-\x1f|&;`$><*?]')


def detect_sketchup_installations() -> list[dict[str, str]]:
    """Detect installed SketchUp executables on Windows without executing them."""
    found: list[dict[str, str]] = []
    seen_paths: set[str] = set()

    # 1. Check standard Program Files directories
    program_dirs = [
        os.environ.get("ProgramFiles", r"C:\Program Files"),
        os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)"),
    ]
    for base in program_dirs:
        if not base:
            continue
        pattern = os.path.join(base, "SketchUp", "SketchUp *", "SketchUp.exe")
        for exe_path in sorted(glob.glob(pattern), reverse=True):
            norm = os.path.normpath(exe_path)
            if os.path.isfile(norm) and norm.lower() not in seen_paths:
                seen_paths.add(norm.lower())
                version_dir = Path(norm).parent.name
                found.append({"version": version_dir, "path": norm})

    return found


def validate_local_dae_path(raw_path: str) -> Path:
    """
    Strictly validate that `raw_path` is a safe, local, existing .dae file.
    Rejects remote URLs, UNC network paths, control characters, and non-.dae files.
    """
    if not raw_path or not isinstance(raw_path, str):
        raise ValueError("Missing file path.")

    cleaned = raw_path.strip().strip('"').strip("'")
    if UNSAFE_CHARS_PATTERN.search(cleaned):
        raise ValueError("File path contains disallowed characters.")

    lowered = cleaned.lower()
    if lowered.startswith(("http://", "https://", "ftp://", "file://", "//", "\\\\")):
        raise ValueError("Remote, URL, or UNC network paths are rejected for security.")

    path = Path(cleaned).resolve(strict=True)
    if not path.is_file():
        raise ValueError(f"Target path is not a file: {path}")

    if path.suffix.lower() not in ALLOWED_EXTENSIONS:
        raise ValueError(f"Only .dae files are allowed, got: {path.suffix}")

    return path


def build_ruby_import_script(dae_path: Path) -> Path:
    """Create a temporary SketchUp Ruby API script to import the validated DAE file."""
    escaped_dae = str(dae_path).replace("\\", "/").replace('"', '\\"')
    ruby_code = (
        "# Auto-generated by MW Hunyuan Bridge Helper\n"
        "begin\n"
        "  model = Sketchup.active_model\n"
        f'  status = model.import("{escaped_dae}", false)\n'
        "  if status\n"
        "    Sketchup.status_text = 'MW Hunyuan Bridge: DAE imported successfully.'\n"
        "  else\n"
        "    UI.messagebox('MW Hunyuan Bridge: SketchUp could not import the DAE file.')\n"
        "  end\n"
        "rescue => e\n"
        "  UI.messagebox(\"MW Hunyuan Bridge import error: #{e.message}\")\n"
        "end\n"
    )
    fd, script_path = tempfile.mkstemp(prefix="mw_hunyuan_import_", suffix=".rb")
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(ruby_code)
    return Path(script_path)


def open_dae_in_sketchup(dae_path: Path) -> str:
    """Launch SketchUp with a Ruby import script for the validated DAE file."""
    installs = detect_sketchup_installations()
    if not installs:
        raise RuntimeError(
            "No SketchUp installation found in Program Files. Please open SketchUp manually and use File -> Import."
        )

    sketchup_exe = installs[0]["path"]
    ruby_script = build_ruby_import_script(dae_path)

    # shell=False ensures no shell interpolation or command injection is possible
    subprocess.Popen([sketchup_exe, "-RubyStartup", str(ruby_script)], shell=False)
    return installs[0]["version"]


def handle_protocol_uri(uri: str) -> int:
    """Parse and execute a validated `mwhunyuan://open?file=...` request."""
    parsed = urllib.parse.urlparse(uri)
    if parsed.scheme.lower() != "mwhunyuan" or parsed.netloc.lower() != "open":
        print(f"Rejected invalid protocol URI: {uri}", file=sys.stderr)
        return 1

    query = urllib.parse.parse_qs(parsed.query)
    raw_file = query.get("file", [""])[0]
    if not raw_file:
        # Fallback: look in user's Downloads folder if only filename was provided
        raw_name = query.get("name", [""])[0]
        if raw_name:
            safe_name = os.path.basename(raw_name)
            candidate = Path.home() / "Downloads" / safe_name
            raw_file = str(candidate)

    try:
        validated_path = validate_local_dae_path(raw_file)
        version = open_dae_in_sketchup(validated_path)
        print(f"Opened {validated_path} in {version}.")
        return 0
    except Exception as exc:
        print(f"MW Hunyuan Bridge Helper error: {exc}", file=sys.stderr)
        return 1


class HelperRequestHandler(http.server.BaseHTTPRequestHandler):
    def _send_json(self, code: int, payload: dict) -> None:
        body = json.dumps(payload).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, OPTIONS")
        self.end_headers()
        self.wfile.write(body)

    def do_OPTIONS(self) -> None:
        self._send_json(204, {})

    def do_GET(self) -> None:
        if self.path == "/health":
            installs = detect_sketchup_installations()
            self._send_json(
                200,
                {
                    "status": "ok",
                    "helper": "mw-hunyuan-bridge-helper",
                    "version": "1.0.0",
                    "sketchupInstalled": len(installs) > 0,
                    "sketchupVersions": [item["version"] for item in installs],
                },
            )
            return
        self._send_json(404, {"error": "Not found"})

    def log_message(self, format: str, *args: object) -> None:
        return


def serve_health_endpoint() -> None:
    server = http.server.ThreadingHTTPServer(("127.0.0.1", HELPER_PORT), HelperRequestHandler)
    print(f"MW Hunyuan Bridge Helper listening on http://127.0.0.1:{HELPER_PORT}/health")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        server.shutdown()


def main() -> int:
    parser = argparse.ArgumentParser(description="MW Hunyuan Bridge SketchUp Integration Helper")
    parser.add_argument("uri", nargs="?", help="Custom protocol URI (mwhunyuan://open?file=...)")
    parser.add_argument("--serve", action="store_true", help="Run localhost health check server")
    parser.add_argument("--detect", action="store_true", help="Print detected SketchUp installations")
    args = parser.parse_args()

    if args.detect:
        print(json.dumps(detect_sketchup_installations(), indent=2))
        return 0

    if args.serve:
        serve_health_endpoint()
        return 0

    if args.uri:
        return handle_protocol_uri(args.uri)

    parser.print_help()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

